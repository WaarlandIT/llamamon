#!/bin/sh
# Install llamamon into its own virtualenv and put the command on PATH.
#
#     ./install.sh
#
# Honours LLAMAMON_VENV (default ~/.venvs/llamamon) and LLAMAMON_BIN (default
# ~/.local/bin). No root: everything stays inside the home directory, so
# removing the tool is an rm -rf on those two paths.

set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
VENV=${LLAMAMON_VENV:-$HOME/.venvs/llamamon}
BIN=${LLAMAMON_BIN:-$HOME/.local/bin}
PY=${PYTHON:-python3}

die() { printf 'install: %s\n' "$*" >&2; exit 1; }

command -v "$PY" >/dev/null 2>&1 || die "$PY not found; install Python 3.9 or newer"
"$PY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' \
    || die "Python 3.9 or newer is required (found $("$PY" -V 2>&1))"

printf 'install: python   %s\n' "$("$PY" -V 2>&1)"
printf 'install: venv     %s\n' "$VENV"
"$PY" -m venv "$VENV" || die "could not create $VENV (is python3-venv installed?)"
"$VENV/bin/pip" install --quiet --upgrade pip >/dev/null 2>&1 || true
"$VENV/bin/pip" install --quiet "$HERE" || die "pip install failed"

mkdir -p "$BIN"
cat > "$BIN/llamamon" <<EOF
#!/bin/sh
# generated by llamamon install.sh -- re-run install.sh after changing $VENV
exec "$VENV/bin/llamamon" "\$@"
EOF
chmod +x "$BIN/llamamon"

printf 'install: command  %s/llamamon\n' "$BIN"
case ":$PATH:" in
  *":$BIN:"*) ;;
  *) printf 'install: %s is not on your PATH; add it with:\n' "$BIN"
     printf '         echo '\''export PATH="%s:$PATH"'\'' >> ~/.profile\n' "$BIN" ;;
esac
command -v sensors >/dev/null 2>&1 \
    || printf 'install: note: lm-sensors not found; temperatures and fan will be missing\n'

printf 'install: done     %s\n' "$("$VENV/bin/llamamon" --version)"
